// Generates packages/chain/src/generated.ts from the compiled contracts (contracts/out) and
// deployments/arc-testnet.json (+ arc-mainnet.json once deployed), so the app always uses the exact ABIs and
// addresses that are deployed. NEXT_PUBLIC_ARC_NETWORK picks one at build time (packages/chain/src/chain.ts).
// Run: pnpm gen   (after `forge build` in contracts/)
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const abi = (file, name) => JSON.parse(readFileSync(`${root}contracts/out/${file}/${name}.json`, "utf8")).abi;
const read = (file) => {
  const path = `${root}deployments/${file}`;
  if (!existsSync(path)) return null;
  const dep = JSON.parse(readFileSync(path, "utf8"));
  if (dep.rehearsal && process.env.ALLOW_REHEARSAL !== "1") {
    throw new Error(`deployments/${file} is from a local rehearsal, not the real chain (a stopped run left it): delete it.`);
  }
  return {
    chainId: dep.chainId,
    block: dep.block,
    usdc: dep.usdc,
    payeeRegistry: dep.contracts.PayeeRegistry.address,
    mandateFactory: dep.contracts.MandateFactory.address,
    mandateImplementation: dep.contracts.MandateImplementation.address,
  };
};

const out = `// GENERATED by scripts/gen-chain.mjs. Do not edit by hand.
export interface Deployment {
  chainId: number;
  block: number;
  usdc: \`0x\${string}\`;
  payeeRegistry: \`0x\${string}\`;
  mandateFactory: \`0x\${string}\`;
  mandateImplementation: \`0x\${string}\`;
}
export const deployments: { testnet: Deployment; mainnet: Deployment | null } = ${JSON.stringify(
  { testnet: read("arc-testnet.json"), mainnet: read("arc-mainnet.json") },
  null,
  2,
)};

export const payeeRegistryAbi = ${JSON.stringify(abi("PayeeRegistry.sol", "PayeeRegistry"))} as const;
export const mandateAbi = ${JSON.stringify(abi("Mandate.sol", "Mandate"))} as const;
export const mandateFactoryAbi = ${JSON.stringify(abi("MandateFactory.sol", "MandateFactory"))} as const;
`;
writeFileSync(`${root}packages/chain/src/generated.ts`, out);
console.log("wrote packages/chain/src/generated.ts");
